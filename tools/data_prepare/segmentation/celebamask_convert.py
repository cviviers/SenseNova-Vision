"""Convert between CelebAMask-HQ segmentation formats (official palette, ids 0-18).

    palette2label   colour-coded maps (e.g. generated by an img2palette model)  -> label maps
                    Every pixel snaps to the nearest official colour; pixels farther than
                    --max_distance from all of them become background (or --unknown_id).
    binary2label    per-class binary masks named <id>_<class>.png (e.g. one img2binseg
                    generation per class)                                         -> label maps
                    Overlaps are resolved with --merge area (smaller masks on top) or
                    class_order (CelebAMask-HQ's own painting order).
    label2palette   label maps                                                    -> official-palette images
    label2parts     label maps -> official per-part annotation files
                    <out>/<id // 2000>/<id:05d>_<class>.png (white on black, only present classes)

Label maps are uint8 PNGs with CelebAMask-HQ class ids, written at 512x512 (the annotation
resolution) and comparable directly with tools/evaluation/segment/evaluate_celebamask.py.
File names must start with the CelebA-HQ image id (e.g. 123.png, 123_hair.png).

    python tools/data_prepare/segmentation/celebamask_convert.py palette2label --input_dir gen/ --output_dir labels/
"""

import argparse
import glob
import os
import re
from collections import defaultdict

import numpy as np
from PIL import Image

from tools.data_prepare.segmentation.celebamask_hq_sft import OFFICIAL_CLASSES, OFFICIAL_COLOURS

SIZE = 512
COLOURS = np.array(OFFICIAL_COLOURS, dtype=np.int32)
CLASS_ID = {name: i for i, name in enumerate(OFFICIAL_CLASSES)}


def leading_id(path):
    match = re.match(r"(\d+)", os.path.basename(path))
    if not match:
        raise ValueError(f"file name must start with the image id: {path}")
    return int(match.group(1))


def palette_to_label(image, max_distance=None, unknown_id=0):
    rgb = np.asarray(image.convert("RGB").resize((SIZE, SIZE), Image.NEAREST), dtype=np.int32)
    dist = ((rgb[:, :, None, :] - COLOURS[None, None]) ** 2).sum(-1)
    label = dist.argmin(-1).astype(np.uint8)
    if max_distance is not None:
        label[np.sqrt(dist.min(-1)) > max_distance] = unknown_id
    return label


def merge_binary(masks, merge):
    """masks: {class_id: bool array}. 'area' paints larger masks first; 'class_order' paints ids ascending."""
    label = np.zeros((SIZE, SIZE), dtype=np.uint8)
    order = sorted(masks, key=lambda c: -int(masks[c].sum())) if merge == "area" else sorted(masks)
    for cid in order:
        label[masks[cid]] = cid
    return label


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["palette2label", "binary2label", "label2palette", "label2parts"])
    parser.add_argument("--input_dir", required=True)
    parser.add_argument("--output_dir", required=True)
    parser.add_argument("--max_distance", type=float, default=None,
                        help="palette2label: pixels farther than this (RGB Euclidean) from every official colour "
                             "become --unknown_id instead of snapping.")
    parser.add_argument("--unknown_id", type=int, default=0, help="palette2label: id for unmatched pixels (e.g. 255).")
    parser.add_argument("--merge", default="area", choices=["area", "class_order"], help="binary2label overlap rule.")
    parser.add_argument("--threshold", type=int, default=127, help="binary2label: grey level counted as foreground.")
    args = parser.parse_args()
    os.makedirs(args.output_dir, exist_ok=True)
    paths = sorted(glob.glob(os.path.join(args.input_dir, "*.png")) + glob.glob(os.path.join(args.input_dir, "*.jpg")))

    if args.command == "palette2label":
        for p in paths:
            label = palette_to_label(Image.open(p), args.max_distance, args.unknown_id)
            Image.fromarray(label).save(os.path.join(args.output_dir, f"{leading_id(p)}.png"))
    elif args.command == "binary2label":
        groups = defaultdict(dict)
        for p in paths:
            match = re.match(r"(\d+)_(\w+)\.(png|jpg)$", os.path.basename(p))
            if not match or match.group(2) not in CLASS_ID:
                continue
            mask = np.asarray(Image.open(p).convert("L").resize((SIZE, SIZE), Image.BILINEAR)) > args.threshold
            groups[int(match.group(1))][CLASS_ID[match.group(2)]] = mask
        for image_id, masks in groups.items():
            Image.fromarray(merge_binary(masks, args.merge)).save(os.path.join(args.output_dir, f"{image_id}.png"))
        paths = list(groups)
    elif args.command == "label2palette":
        for p in paths:
            label = np.asarray(Image.open(p))
            Image.fromarray(COLOURS.astype(np.uint8)[label]).save(os.path.join(args.output_dir, f"{leading_id(p)}.png"))
    else:  # label2parts
        for p in paths:
            image_id, label = leading_id(p), np.asarray(Image.open(p))
            folder = os.path.join(args.output_dir, str(image_id // 2000))
            os.makedirs(folder, exist_ok=True)
            for cid in np.unique(label):
                if 0 < cid < len(OFFICIAL_CLASSES):
                    Image.fromarray(np.where(label == cid, 255, 0).astype(np.uint8)).save(
                        os.path.join(folder, f"{image_id:05d}_{OFFICIAL_CLASSES[cid]}.png"))
    print(f"[celebamask_convert] {args.command}: {len(paths)} inputs -> {args.output_dir}")


if __name__ == "__main__":
    main()
