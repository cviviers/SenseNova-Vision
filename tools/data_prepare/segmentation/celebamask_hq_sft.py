"""Convert CelebAMask-HQ into SenseNova-Vision fine-tuning data.

Every task uses ONE fixed, explicit prompt (or one template whose only variable
is the CelebAMask-HQ class), identical for every image. Segmentation maps use
the official CelebAMask-HQ colour list and class order (checked at import).

* ``img2palette``  photo -> full colour-coded segmentation map (official palette)
                   group ``seg_instance_sft`` (SegJSONLIterableDataset), answer "<SEG>".
* ``img2palette_partial``  photo -> map of a requested SUBSET of classes in the official
                   colours, every other pixel black. The subset (any of the 18 classes, size 1-17 by
                   default) is the only variable in the prompt; ``--partial_per_image`` subsets per image.
                   group ``seg_gcg_sft`` (SegJSONLIterableDataset), answer "<SEG>".
* ``img2binseg``   photo -> binary mask of ONE CelebAMask-HQ class (white on black)
                   group ``seg_sft`` (SegJSONLIterableDataset), answer "<SEG>".
                   By default all 18 classes are requested for every image; absent
                   classes get an all-black target, so the model learns to return an
                   empty mask instead of hallucinating one (``--binary_classes present``
                   keeps only the classes present in the image).
* ``seg2img``      official-palette segmentation map -> photo
                   group ``general_edit`` (EditJSONLIterableDataset).

Prompts, palette and label loading live in data/celebamask.py (``IMG2PALETTE_PROMPT``,
``partial_prompt(class_ids)``, ``binary_prompt(class_id)``, ``seg2img_prompt(label)``), shared with the
training-time generator ``CelebAMaskMultiTaskDataset`` that produces all of these on the fly. Convert generated outputs
back to CelebAMask-HQ label maps / per-part annotation files with
tools/data_prepare/segmentation/celebamask_convert.py.

Everything is written at 512x512 (the annotation resolution).

Output layout (``--output_dir``):
    images/<id>.jpg                  photo, 512x512
    masks/palette/<id>.png           official-palette segmentation map
    masks/partial/<id>_<classes>.png partial maps
    masks/binary/<id>_<class>.png    binary mask per present class
    masks/binary/empty.png           shared all-black target for absent classes
    <split>_<task>.jsonl             one file per task
    celebamask_hq_<split>.yaml       dataset config for train/finetune_lora.py
    <split>_examples.md / .png       examples for review (with --examples)

    python tools/data_prepare/segmentation/celebamask_hq_sft.py --split train --output_dir datas/celebamask_hq_sft
"""

import argparse
import json
import os
import random

import numpy as np
from PIL import Image

from data.celebamask import (
    CLASS_NAMES,
    FACE_CLASS_IDS,
    IMG2PALETTE_PROMPT,
    PALETTE,
    SIZE,
    SPLIT_RANGES,
    binary_image,
    binary_prompt,
    load_label_map,
    load_photo,
    load_split_ids,
    palette_image,
    partial_prompt,
    seg2img_prompt,
)
from tools.data_prepare.segmentation.common.prompts import DEFAULT_IMAGE_TOKEN, DEFAULT_SEG_TOKEN

# Official CelebAMask-HQ class order and colour list; data/celebamask.py must match them exactly.
OFFICIAL_CLASSES = ["background", "skin", "nose", "eye_g", "l_eye", "r_eye", "l_brow", "r_brow", "l_ear", "r_ear",
                    "mouth", "u_lip", "l_lip", "hair", "hat", "ear_r", "neck_l", "neck", "cloth"]
OFFICIAL_COLOURS = [[0, 0, 0], [204, 0, 0], [76, 153, 0], [204, 204, 0], [51, 51, 255], [204, 0, 204], [0, 255, 255],
                    [255, 204, 204], [102, 51, 0], [255, 0, 0], [102, 204, 0], [255, 255, 0], [0, 0, 153],
                    [0, 0, 204], [255, 51, 153], [0, 204, 204], [0, 51, 0], [255, 153, 51], [0, 204, 0]]
assert PALETTE.tolist() == OFFICIAL_COLOURS, "palette differs from the official CelebAMask-HQ colours"
assert CLASS_NAMES == OFFICIAL_CLASSES, "class order differs from CelebAMask-HQ"

TASKS = {"img2palette": "seg_instance_sft", "img2palette_partial": "seg_gcg_sft", "img2binseg": "seg_sft",
         "seg2img": "general_edit"}


def write_config(out, split, counts, weights):
    root = os.path.abspath(out)
    transforms = ["  image_transform_args:", "    image_stride: 16", "    max_image_size: 512", "    min_image_size: 512",
                  "  vit_image_transform_args:", "    image_stride: 14", "    max_image_size: 518",
                  "    min_image_size: 224"]
    lines = ["# Generated by tools/data_prepare/segmentation/celebamask_hq_sft.py",
             "# Use with: bash scripts/finetune_lora.sh <this file> --output_dir results/celebamask_lora", ""]
    for task, group in TASKS.items():
        if task not in counts:
            continue
        lines += [f"{group}:", "  datasets:", f"    celebamask_{task}:", f"      data_dir: {root}",
                  f"      jsonl_path: {root}/{split}_{task}.jsonl", f"      num_total_samples: {counts[task]}",
                  *transforms]
        if group == "general_edit":
            lines.append("  task_prompt: raw_prompt")
        else:  # no_prefix_promt passes the fixed prompt through unchanged (raw_prompt is not valid for seg datasets)
            lines += ["  task_prompt: no_prefix_promt", "  think_mode: False"]
        lines += ["  shuffle_lines: True", "  shuffle_seed: 0", f"  weight: {weights[task]}", ""]
    with open(os.path.join(out, f"celebamask_hq_{split}.yaml"), "w") as f:
        f.write("\n".join(lines))


def write_examples(out, split, examples):
    """Markdown with the raw JSON records plus a PNG sheet: input | target | prompt."""
    import textwrap

    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    md = [f"# CelebAMask-HQ fine-tuning examples ({split})", "",
          f"Visual sheet: `{split}_examples.png`. Paths are relative to this directory.", ""]
    for task, (image_id, rec) in examples.items():
        md += [f"## {task} · image {image_id}", "```json", json.dumps(rec, indent=2, ensure_ascii=False), "```", ""]
    with open(os.path.join(out, f"{split}_examples.md"), "w") as f:
        f.write("\n".join(md))

    fig, axes = plt.subplots(len(examples), 3, figsize=(17, 3.6 * len(examples)),
                             gridspec_kw={"width_ratios": [1, 1, 3.4]}, facecolor="#fcfcfb")
    plt.subplots_adjust(left=0.01, right=0.99, top=0.95, bottom=0.02, wspace=0.04, hspace=0.15)
    for r, (task, (image_id, rec)) in enumerate(examples.items()):
        if task.startswith("seg2img"):
            paths, titles = rec["image"], ("INPUT (segmentation map)", "TARGET (photo)")
            text = f"INSTRUCTION: {rec['instruction']}"
        else:
            paths, titles = (rec["image"], rec["seg"]), ("INPUT (photo)", "TARGET (mask)")
            text = f"HUMAN: {rec['conversations'][0]['value']}\n\nGPT: {rec['conversations'][1]['value']}"
        for c, (path, title) in enumerate(zip(paths, titles)):
            axes[r, c].imshow(Image.open(os.path.join(out, path)))
            axes[r, c].set_xticks([]), axes[r, c].set_yticks([])
            axes[r, c].set_title(title, fontsize=9, loc="left")
        axes[r, 2].axis("off")
        axes[r, 2].text(0, 1, f"{task}  ·  image {image_id}", fontsize=11,
                        fontweight="bold", va="top")
        axes[r, 2].text(0, 0.88, "\n".join(textwrap.fill(p, 115) for p in text.split("\n")), fontsize=8.5,
                        va="top", family="DejaVu Sans Mono")
    fig.savefig(os.path.join(out, f"{split}_examples.png"), dpi=90, facecolor="#fcfcfb")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dataset_root", default="/datasets/CelebAMask-HQ/CelebAMask-HQ")
    parser.add_argument("--output_dir", default="datas/celebamask_hq_sft")
    parser.add_argument("--split", default="train", choices=list(SPLIT_RANGES))
    parser.add_argument("--limit", type=int, default=None, help="First N images of the split (for review).")
    parser.add_argument("--tasks", default=",".join(TASKS), help=f"Subset of {list(TASKS)}.")
    parser.add_argument("--partial_per_image", type=int, default=2,
                        help="img2palette_partial: random class subsets per image.")
    parser.add_argument("--partial_size_range", default="1,17", help="img2palette_partial: min,max classes per subset.")
    parser.add_argument("--seed", type=int, default=0, help="Seed for the partial subsets.")
    parser.add_argument("--binary_classes", default="all", choices=["all", "present"],
                        help="img2binseg: request all 18 classes (absent ones -> empty mask) or only present ones.")
    parser.add_argument("--weights", default="img2palette=0.2,img2palette_partial=0.2,img2binseg=0.3,seg2img=0.3",
                        help="Sampling weight of each task's group in the generated YAML.")
    parser.add_argument("--examples", action="store_true", help="Write <split>_examples.md/.png for review.")
    args = parser.parse_args()

    tasks = [t for t in args.tasks.split(",") if t]
    unknown = set(tasks) - set(TASKS)
    if unknown:
        parser.error(f"unknown tasks {sorted(unknown)}")
    weights = {k: float(v) for k, v in (item.split("=") for item in args.weights.split(","))}

    out = args.output_dir
    for d in ("images", "masks/palette", "masks/partial", "masks/binary"):
        os.makedirs(os.path.join(out, d), exist_ok=True)
    empty_rel = "masks/binary/empty.png"
    Image.new("RGB", (SIZE, SIZE)).save(os.path.join(out, empty_rel))
    ids = load_split_ids(args.dataset_root, args.split)[: args.limit]
    rng = random.Random(args.seed)
    lo, hi = (int(v) for v in args.partial_size_range.split(","))
    counts = {t: 0 for t in tasks}
    examples = {}
    files = {t: open(os.path.join(out, f"{args.split}_{t}.jsonl"), "w") for t in tasks}

    for n, image_id in enumerate(ids, 1):
        image_rel, palette_rel = f"images/{image_id}.jpg", f"masks/palette/{image_id}.png"
        if not os.path.exists(os.path.join(out, image_rel)):
            load_photo(args.dataset_root, image_id).save(os.path.join(out, image_rel), quality=95)
        label = load_label_map(args.dataset_root, image_id)
        palette_image(label).save(os.path.join(out, palette_rel))
        present = {int(c) for c in np.unique(label) if c}

        records = []
        if "img2palette" in tasks:
            records.append(("img2palette", "img2palette", seg_record(image_rel, palette_rel, IMG2PALETTE_PROMPT)))
        if "img2palette_partial" in tasks:
            for _ in range(args.partial_per_image):
                subset = sorted(rng.sample(FACE_CLASS_IDS, rng.randint(lo, hi)))
                rel = f"masks/partial/{image_id}_{'-'.join(CLASS_NAMES[c] for c in subset)}.png"
                if len(rel) > 200:  # keep file names short for large subsets
                    rel = f"masks/partial/{image_id}_{'-'.join(str(c) for c in subset)}.png"
                palette_image(label, subset).save(os.path.join(out, rel))
                key = f"img2palette_partial ({len(subset)} classes)"
                records.append(("img2palette_partial", key, seg_record(image_rel, rel, partial_prompt(subset))))
        if "img2binseg" in tasks:
            for cid in FACE_CLASS_IDS:
                if cid in present:
                    rel = f"masks/binary/{image_id}_{CLASS_NAMES[cid]}.png"
                    binary_image(label, cid).save(os.path.join(out, rel))
                    key = "img2binseg (present class)"
                elif args.binary_classes == "all":
                    rel, key = empty_rel, "img2binseg (absent class)"
                else:
                    continue
                records.append(("img2binseg", key, seg_record(image_rel, rel, binary_prompt(cid))))
        if "seg2img" in tasks:
            records.append(("seg2img", "seg2img", {"image": [palette_rel, image_rel], "instruction": seg2img_prompt(label)}))

        for task, key, rec in records:
            files[task].write(json.dumps(rec, ensure_ascii=False) + "\n")
            counts[task] += 1
            n_partial = sum(k.startswith("img2palette_partial") for k in examples)
            if not key.startswith("img2palette_partial") or n_partial < 4:  # a few partial cases are enough
                examples.setdefault(key, (image_id, rec))
        if n % 1000 == 0:
            print(f"[celebamask_sft] {n}/{len(ids)} images", flush=True)

    for f in files.values():
        f.close()
    write_config(out, args.split, counts, weights)
    if args.examples:
        write_examples(out, args.split, examples)
    print(f"[celebamask_sft] {len(ids)} images -> {out}: {counts}")


def seg_record(image_rel, seg_rel, prompt):
    return {"image": image_rel, "seg": seg_rel,
            "conversations": [{"from": "human", "value": DEFAULT_IMAGE_TOKEN + prompt},
                              {"from": "gpt", "value": DEFAULT_SEG_TOKEN}]}


if __name__ == "__main__":
    main()
